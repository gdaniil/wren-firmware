#!/usr/bin/env python3
"""Build Wren's built-in UI fonts (1-bit, flash) from Golos Text and IBM Plex Mono.

Sizes are em pixels on the device, matching the design canvas (528x792 X3 mocks are 1:1 device px).
Runs the upstream converter (lib/EpdFont/scripts/fontconvert.py) unchanged on disk; only the size
argument is made fractional in memory so an em of N px is exact (the converter works in pt at 150 dpi).

Usage: python scripts/wren/build_ui_fonts.py
Output: lib/EpdFont/builtinFonts/wren_*.h and src/wren/ui/WrenFontIds.generated.h
"""

import contextlib
import hashlib
import io
import os
import sys
from pathlib import Path
from urllib.parse import quote
from urllib.request import urlopen

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parents[2]
CACHE = ROOT / ".cache" / "wren-fonts"
OUT = ROOT / "lib" / "EpdFont" / "builtinFonts"
IDS = ROOT / "src" / "wren" / "ui" / "WrenFontIds.generated.h"
CONVERTER = ROOT / "lib" / "EpdFont" / "scripts" / "fontconvert.py"
REVISION = "29b4ec6df2522a8aee279414b78a07910b065874"

SOURCES = {
    "golostext": "GolosText[wght].ttf",
    "ibmplexmono": "IBMPlexMono-SemiBold.ttf",
}

# Digits only, for the go-to screen's big number: space, %, -, ., 0-9.
NUMERALS = [(0x20, 0x20), (0x25, 0x25), (0x2D, 0x2E), (0x30, 0x39)]

# Headline set for the 56 px state titles: ASCII, Russian and Ukrainian letters, apostrophe. Keeps the
# biggest font small; the full default set at 56 px would cost about twice the flash.
HEADLINE = [(0x20, 0x7E), (0x400, 0x45F), (0x490, 0x491), (0x2019, 0x2019)]

# name, source, wght (None = static file), em px, code point intervals (None = the converter's default set)
FONTS = [
    ("wren_golos_18", "golostext", 400, 18, None),
    ("wren_golos_24", "golostext", 400, 24, None),
    ("wren_golos_40", "golostext", 400, 40, None),
    ("wren_golos_32", "golostext", 400, 32, None),
    ("wren_golos_56_headline", "golostext", 400, 56, HEADLINE),
    ("wren_golos_18_semibold", "golostext", 600, 18, None),
    ("wren_golos_160_digits", "golostext", 400, 160, NUMERALS),
    ("wren_mono_16", "ibmplexmono", None, 16, None),
]


def fetch(family, name):
    path = CACHE / family / name
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        url = f"https://raw.githubusercontent.com/google/fonts/{REVISION}/ofl/{family}/{quote(name)}"
        with urlopen(url, timeout=60) as response:
            path.write_bytes(response.read())
    return path


def instance(path, wght):
    out = CACHE / f"ui-{path.stem.split('[')[0]}-{wght}.ttf"
    if not out.exists():
        font = TTFont(path)
        instancer.instantiateVariableFont(font, {"wght": wght}, inplace=True)
        font.save(out)
    return out


def convert(name, font_path, em_px, only=None):
    source = CONVERTER.read_text()
    patched = source.replace('parser.add_argument("size", type=int,', 'parser.add_argument("size", type=float,')
    patched = patched.replace("face.set_char_size(size << 6, size << 6, 150, 150)",
                              "face.set_char_size(round(size * 64), round(size * 64), 150, 150)")
    patched = patched.replace("unmerged_intervals = sorted(intervals + add_ints)",
                              "unmerged_intervals = sorted(WREN_ONLY or intervals + add_ints)")
    if (patched.count("type=float") != 1 or "round(size * 64)" not in patched
            or "WREN_ONLY or" not in patched):
        sys.exit("fontconvert.py changed upstream; update build_ui_fonts.py")
    pt = em_px * 72.0 / 150.0
    argv, cwd = sys.argv, os.getcwd()
    os.chdir(ROOT)  # relative paths keep the generated "Command used" line machine-independent
    sys.argv = [str(CONVERTER.relative_to(ROOT)), name, repr(pt), str(font_path.relative_to(ROOT))]
    buffer = io.StringIO()
    try:
        with contextlib.redirect_stdout(buffer):
            exec(compile(patched, str(CONVERTER), "exec"),
                 {"__name__": "__main__", "__file__": str(CONVERTER), "WREN_ONLY": only})
    finally:
        sys.argv = argv
        os.chdir(cwd)
    (OUT / f"{name}.h").write_text(buffer.getvalue())
    print(f"{name}.h  {em_px}px em  ({pt:.3f} pt @150dpi)")


def font_id(name):
    # Same scheme as lib/EpdFont/scripts/build-font-ids.sh: SHA-256 of the header, mod 2^32, signed.
    digest = int(hashlib.sha256((OUT / f"{name}.h").read_bytes()).hexdigest(), 16)
    return digest % (2**32) - (2**31)


def write_ids():
    lines = ["// Generated by scripts/wren/build_ui_fonts.py. Do not edit.", "#pragma once", ""]
    for name, *_ in FONTS:
        lines.append(f"#define {name.upper()}_FONT_ID ({font_id(name)})")
    lines.append("")
    for name, *_ in FONTS:
        lines.append(f'static_assert({name.upper()}_FONT_ID != 0, "Font ID collision with sentinel");')
    IDS.write_text("\n".join(lines) + "\n")


def main():
    for name, family, wght, em_px, only in FONTS:
        path = fetch(family, SOURCES[family])
        fetch(family, "OFL.txt")
        if wght is not None:
            path = instance(path, wght)
        convert(name, path, em_px, only)
    write_ids()


if __name__ == "__main__":
    main()
