#!/usr/bin/env python3
"""Generate the built-in Literata faces using the SD font weights and x-height calibration."""
import contextlib
import hashlib
import io
import json
import os
import sys

import freetype
from build_fonts import CACHE, FILES, ROOT, find_em, ink_height, instance, mono
from download_fonts import main as download

CONVERTER = ROOT / 'lib/EpdFont/scripts/fontconvert.py'
OUT = ROOT / 'lib/EpdFont/builtinFonts'
IDS = ROOT / 'src/wren/typography/BuiltinLiterataIds.h'


def main():
    download()
    weights = json.loads((ROOT / 'scripts/wren/weights.json').read_text())['Literata']
    source_text = CONVERTER.read_text()
    patched = source_text.replace('parser.add_argument("size", type=int,', 'parser.add_argument("size", type=float,')
    patched = patched.replace('face.set_char_size(size << 6, size << 6, 150, 150)',
                              'face.set_char_size(round(size * 64), round(size * 64), 72, 72)')
    patched = patched.replace('ppem = size * 150.0 / 72.0', 'ppem = size')
    if patched == source_text or 'size << 6' in patched or 'ppem = size * 150.0 / 72.0' in patched:
        raise RuntimeError('fontconvert.py sizing changed; update this wrapper')
    ids = []
    for xh in (12, 14, 17):
        paths = []
        for style, source_index, weight_key in (('regular', 0, 'regular'), ('bold', 0, 'bold'),
                                                ('italic', 1, 'regular'), ('bolditalic', 1, 'bold')):
            source = CACHE / 'literata' / FILES['literata'][source_index]
            weight = weights[str(xh)][weight_key]
            em = find_em(source, weight, xh)
            static = CACHE / f'builtin-Literata-{xh}-{style}.ttf'
            instance(source, weight, em, static)
            face = freetype.Face(str(static))
            face.set_char_size(round(em * 64), round(em * 64), 72, 72)
            if ink_height(mono(face, 'x')) != xh:
                raise RuntimeError(f'{static} does not have x-height {xh}')
            name = f'wren_literata_{xh}_{style}'
            argv, cwd = sys.argv, os.getcwd()
            os.chdir(ROOT)
            sys.argv = [str(CONVERTER.relative_to(ROOT)), name, str(em), str(static.relative_to(ROOT)),
                        str((ROOT / 'lib/EpdFont/builtinFonts/source/NotoSans' /
                             f'NotoSans-{dict(regular="Regular", bold="Bold", italic="Italic", bolditalic="BoldItalic")[style]}.ttf').relative_to(ROOT)),
                        '--2bit', '--compress', '--pnum', '--zopfli']
            output = io.StringIO()
            try:
                with contextlib.redirect_stdout(output):
                    exec(compile(patched, str(CONVERTER), 'exec'), {'__name__': '__main__', '__file__': str(CONVERTER)})
            finally:
                sys.argv = argv
                os.chdir(cwd)
            path = OUT / f'{name}.h'
            path.write_text(output.getvalue())
            paths.append(path)
        value = sum(int(hashlib.sha256(p.read_bytes()).hexdigest(), 16) for p in paths) % (2 ** 32) - 2 ** 31
        if value == 0:
            raise RuntimeError('Font ID collides with sentinel')
        ids.append(f'#define WREN_LITERATA_{xh}_FONT_ID ({value})')
    IDS.write_text('// Generated by scripts/wren/build_builtin_literata.py. Do not edit.\n#pragma once\n\n' + '\n'.join(ids) + '\n')


if __name__ == '__main__':
    main()
